package main

import (
	"strings"

	"github.com/dave/jennifer/jen"

	"github.com/osapi-io/osapi/internal/behavior"
)

// module is the module path, stripped from a package path to find its
// directory in the repository.
const module = "github.com/osapi-io/osapi"

const (
	echoPath    = "github.com/labstack/echo/v5"
	apiPath     = module + "/internal/controller/api/behavior"
	apitestPath = module + "/internal/behavior/apitest"
	httpPath    = "net/http"
)

// generated heads every file the generator writes.
const generated = "Code generated by internal/behavior/gen. DO NOT EDIT."

// pkgPath is the import path of b's package, where its types are.
func pkgPath(
	b *behavior.Behavior,
) string {
	return b.Methods[0].In.PkgPath()
}

// genFile is a new file in b's gen package.
func genFile(
	b *behavior.Behavior,
) *jen.File {
	f := jen.NewFilePathName(pkgPath(b)+"/gen", "gen")
	header(f, b)

	return f
}

// genTestFile is a new file in b's gen package's external test package.
func genTestFile(
	b *behavior.Behavior,
) *jen.File {
	f := jen.NewFilePathName(pkgPath(b)+"/gen_test", "gen_test")
	header(f, b)

	return f
}

func header(
	f *jen.File,
	b *behavior.Behavior,
) {
	f.HeaderComment("Code generated by internal/behavior/gen from " +
		strings.TrimPrefix(pkgPath(b), module+"/") + ". DO NOT EDIT.")
	f.ImportName(echoPath, "echo")
	f.ImportAlias(apiPath, "behaviorapi")
	f.ImportName(pkgPath(b)+"/gen", "gen")
}

// multi lays out a group one item to a line, as the house style writes
// parameter lists and tables.
func multi(
	open string,
	closing string,
	items ...jen.Code,
) *jen.Statement {
	return jen.Custom(
		jen.Options{Open: open, Close: closing, Separator: ",", Multi: true},
		items...)
}

// params is a parameter list, one parameter to a line.
func params(
	items ...jen.Code,
) *jen.Statement {
	return multi("(", ")", items...)
}

// suiteRunner adds the test function that runs a suite.
func suiteRunner(
	f *jen.File,
	name string,
) {
	f.Line()
	f.Func().Id("Test" + name).Add(params(jen.Id("t").Op("*").Qual("testing", "T"))).Block(
		jen.Qual(suitePath, "Run").Call(jen.Id("t"), jen.New(jen.Id(name))),
	)
}

// comment adds text to f as // lines wrapped at 76 columns, the way the
// repository's comments are written. jen renders a comment with a newline
// in it as a block comment, so each line is its own.
func comment(
	f *jen.File,
	text string,
) {
	for _, line := range wrap(text, 76) {
		f.Comment(line)
	}
}

func wrap(
	text string,
	width int,
) []string {
	var lines []string
	var line string
	for _, word := range strings.Fields(text) {
		if line != "" && len(line)+1+len(word) > width {
			lines = append(lines, line)
			line = word

			continue
		}
		if line != "" {
			line += " "
		}
		line += word
	}

	return append(lines, line)
}
