const module = "github.com/osapi-io/osapi"

// generated heads each file this step writes.
const generated = "Code generated by internal/behavior/gen/group. DO NOT EDIT."

const commandtestPath = module + "/internal/behavior/command/commandtest"

// fullSpec is the spec of the API, from the root of the repository: the
// controller serves it, and the SDK client, the UI client and the API docs
// are generated from it.
const fullSpec = "internal/controller/api/gen/api.yaml"

func main() {
	// A generated page shows each time in UTC, so it does not change
	// with the time zone of the machine that writes it.
	time.Local = time.UTC

	root := flag.String("root", ".", "the root of the repository")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "behavior spec:", err)
		os.Exit(1)
	}
}

func run(
	root string,
) error {
	w := &genfile.Writer{Root: root}
	var specs []spec
	for _, b := range behavior.All() {
		if !b.API {
			continue
		}
		g := behavior.GroupOf(b)
		if g == nil {
			return fmt.Errorf("%s has no endpoint group: run internal/behavior/gen first", b.Name)
		}
		dir := filepath.Join(strings.TrimPrefix(b.Methods[0].In.PkgPath(), module+"/"), "gen")
		doc, err := openAPI(g, strings.ToUpper(g.Name[:1])+g.Name[1:]+" API", g.Doc+".")
		if err != nil {
			return fmt.Errorf("%s: %w", b.Name, err)
		}
		if err := write(w, filepath.Join(dir, "api.yaml"), doc); err != nil {
			return fmt.Errorf("%s: %w", b.Name, err)
		}
		specs = append(specs, spec{dir: dir, doc: doc})
		if err := routes(w, dir, g); err != nil {
			return fmt.Errorf("%s: %w", b.Name, err)
		}
		if b.CLI {
			if err := commands(w, dir, b, g); err != nil {
				return fmt.Errorf("%s: %w", b.Name, err)
			}
		}
	}
	if err := full(w, specs); err != nil {
		return err
	}

	return w.Flush()
}

// spec is the spec of one group, and the directory its gen/api.yaml is in.
type spec struct {
	dir string
	doc *openapi3.T
}

// full writes the spec of the API, fullSpec, from each endpoint group that
// the controller serves and each behavior's spec, behaviors. The endpoint
// groups come first, in the order of their directories, then the
// behaviors, in the order of behavior.All: the order of their commands, so
// sshkey is after user.
func full(
	w *genfile.Writer,
	behaviors []spec,
) error {
	var groups []spec
	for _, g := range endpoint.All() {
		if g.Deps == nil {
			continue
		}
		doc, err := openAPI(g, g.Title, "")
		if err != nil {
			return fmt.Errorf("%s: %w", g.Name, err)
		}
		dir := filepath.Join(strings.TrimPrefix(g.Deps.PkgPath(), module+"/"), "gen")
		groups = append(groups, spec{dir: dir, doc: doc})
	}
	slices.SortFunc(groups, func(a, b spec) int { return strings.Compare(a.dir, b.dir) })
	var docs []*openapi3.T
	for _, s := range append(groups, behaviors...) {
		docs = append(docs, s.doc)
	}
	text, err := specgen.Full(docs, generated)
	if err != nil {
		return err
	}

	return w.Write(fullSpec, text)
}

// openAPI is the spec of g, with title, which the full spec puts in front
// of its tag, and description, when it has one.
func openAPI(
	g *endpoint.Group,
	title string,
	description string,
) (*openapi3.T, error) {
	doc, err := endpoint.OpenAPI(g)
	if err != nil {
		return nil, err
	}
	doc.Info.Title = title
	if description != "" {
		doc.Info.Description = description
	}

	return doc, nil
}

// write writes doc at path.
func write(
	w *genfile.Writer,
	path string,
	doc *openapi3.T,
) error {
	text, err := specgen.Encode(doc, generated)
	if err != nil {
		return err
	}

	return w.Write(path, text)
}

// routes writes the group's route table, gen/api.go, and its decoders,
// gen/decode.go, with the endpoint layer's route writer, so a behavior is
// served by the same code as an endpoint.
func routes(
	w *genfile.Writer,
	dir string,
	g *endpoint.Group,
) error {
	pkg := module + "/" + filepath.ToSlash(dir)
	for name, write := range map[string]func(f *jen.File){
		"api.go":    func(f *jen.File) { routegen.Routes(f, g, pkg) },
		"decode.go": func(f *jen.File) { routegen.Decoders(f, g) },
	} {
		f := newFile(pkg, "gen")
		write(f)
		if err := w.Go(filepath.Join(dir, name), f); err != nil {
			return err
		}
	}

	return nil
}

// commands writes the group's commands, gen/cli.go, with the endpoint
// layer's command writer, and gen/cli_public_test.go: each example's command
// line, run through them, sends the request that the endpoint command
// runtime builds from the example's input.
func commands(
	w *genfile.Writer,
	dir string,
	b *behavior.Behavior,
	g *endpoint.Group,
) error {
	pkg := module + "/" + filepath.ToSlash(dir)
	cli := newFile(pkg, "gen")
	commandgen.Commands(cli, g, pkg)
	if err := w.Go(filepath.Join(dir, "cli.go"), cli); err != nil {
		return err
	}

	// A secret's example reads its value from standard input, so the table
	// has a column for it only when an example does.
	stdin := false
	for _, bm := range b.Methods {
		for _, ex := range bm.Examples {
			stdin = stdin || command.Stdin(ex.Input) != ""
		}
	}
	var rows []jen.Code
	for _, bm := range b.Methods {
		m := g.Method(bm.Name)
		for _, ex := range bm.Examples {
			path, body, _, err := endpointcommand.Build(g, m, requestOf(m.In, "server1", ex.Input))
			if err != nil {
				return fmt.Errorf("%s example %q: %w", bm.Name, ex.Doc, err)
			}
			args := append(
				append([]string{}, g.CommandPath()...),
				m.CommandName(),
				"--target",
				"server1",
			)
			args = append(args, command.Args(ex.Input)...)
			lits := make([]jen.Code, 0, len(args))
			for _, a := range args {
				lits = append(lits, jen.Lit(a))
			}
			row := []jen.Code{
				jen.Id("name").Op(":").Lit("when the example " + strconv.Quote(ex.Doc) + " is run"),
				jen.Id("args").Op(":").Index().String().Values(lits...),
			}
			if in := command.Stdin(ex.Input); in != "" {
				row = append(row, jen.Id("stdin").Op(":").Lit(in))
			}
			row = append(row, jen.Id("want").Op(":").Qual(commandtestPath, "Request").Add(
				genutil.Multi("{", "}",
					jen.Id("Method").Op(":").Lit(m.HTTPMethod()),
					jen.Id("Path").Op(":").Lit(path),
					jen.Id("Body").Op(":").Lit(string(body)),
				)))
			rows = append(rows, genutil.Multi("{", "}", row...))
		}
	}

	t := newFile(pkg+"_test", "gen_test")
	t.Comment("CLIPublicTestSuite runs each example's command line through the generated commands.")
	t.Type().Id("CLIPublicTestSuite").Struct(jen.Qual("github.com/stretchr/testify/suite", "Suite"))
	t.Line()
	t.Comment("TestCommands runs each example's command line and checks the request it sends.")
	fields := []jen.Code{jen.Id("name").String(), jen.Id("args").Index().String()}
	sent := jen.Qual(commandtestPath, "Sent").
		Call(jen.Id("s").Dot("T").Call(), jen.Id("tc").Dot("args"))
	if stdin {
		fields = append(fields, jen.Id("stdin").String())
		sent = jen.Qual(commandtestPath, "SentWith").Call(
			jen.Id("s").Dot("T").Call(), jen.Id("tc").Dot("args"), jen.Id("tc").Dot("stdin"))
	}
	fields = append(fields, jen.Id("want").Qual(commandtestPath, "Request"))
	t.Func().Params(jen.Id("s").Op("*").Id("CLIPublicTestSuite")).Id("TestCommands").Params().Block(
		jen.Id("tests").Op(":=").Index().Struct(fields...).Add(genutil.Multi("{", "}", rows...)),
		jen.Line(),
		jen.For(jen.List(jen.Id("_"), jen.Id("tc")).Op(":=").Range().Id("tests")).Block(
			jen.Id("s").Dot("Run").Call(jen.Id("tc").Dot("name"), jen.Func().Params().Block(
				jen.Id("s").Dot("Equal").Call(jen.Id("tc").Dot("want"), sent),
			)),
		),
	)
	t.Line()
	t.Func().Id("TestCLIPublicTestSuite").Params(jen.Id("t").Op("*").Qual("testing", "T")).Block(
		jen.Qual("github.com/stretchr/testify/suite", "Run").
			Call(jen.Id("t"), jen.New(jen.Id("CLIPublicTestSuite"))),
	)
	t.Anon(pkg)

	return w.Go(filepath.Join(dir, "cli_public_test.go"), t)
}

// requestOf is the request of type t for target with input, a value of the
// behavior method's input type: each field of the request, or of its body,
// from the input field of the same name.
func requestOf(
	t reflect.Type,
	target string,
	input any,
) any {
	in := reflect.ValueOf(input)
	req := reflect.New(t).Elem()
	req.FieldByName("Hostname").SetString(target)
	from := func(dst reflect.Value, dt reflect.Type) {
		for i := range dt.NumField() {
			if src := in.FieldByName(dt.Field(i).Name); src.IsValid() {
				dst.Field(i).Set(src)
			}
		}
	}
	for i := range t.NumField() {
		f := t.Field(i)
		switch {
		case f.Name == "Hostname":
		case f.Tag.Get("in") == "body":
			from(req.Field(i), f.Type)
		default:
			if src := in.FieldByName(f.Name); src.IsValid() {
				req.Field(i).Set(src)
			}
		}
	}

	return req.Interface()
}

// newFile is a new generated file of the package at path.
func newFile(
	path string,
	name string,
) *jen.File {
	f := jen.NewFilePathName(path, name)
	f.HeaderComment(generated)
	f.ImportName("github.com/osapi-io/osapi/internal/controller/endpoint/server", "server")
	f.ImportName("github.com/labstack/echo/v5", "echo")
	f.ImportName("github.com/spf13/cobra", "cobra")

	return f
}
