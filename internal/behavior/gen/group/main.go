// Command group writes what the endpoint layer makes from each behavior's
// endpoint group: its spec, routes, decoders and commands. For each behavior
// with an API, from its gen/group.go, which internal/behavior/gen writes, it
// writes the behavior's gen/api.yaml. Then it writes the full spec of the
// API, internal/controller/api/gen/api.yaml, from these specs and those of
// the endpoint groups. It runs after internal/behavior/gen, once the groups
// compile.
package main

