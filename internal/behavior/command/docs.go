// exampleHost is the target of each example command.
const exampleHost = "web-01"

// DocsDir is where a behavior's pages are written, relative to the
// repository root: its own directory in the docs site's Behaviors section.
func DocsDir(
	b *behavior.Behavior,
) string {
	return "docs/docs/sidebar/behaviors/" + b.Name
}

// IndexPage is the behavior's page: what it manages, where it is served, its
// methods, its settings, and how to inspect it. Each method has a page of its
// own under it.
func IndexPage(
	b *behavior.Behavior,
) string {
	var sb strings.Builder
	sb.WriteString("---\nsidebar_position: 1\n---\n\n")
	sb.WriteString("<!-- Code generated by osapi gen. DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&sb, "# %s\n\n%s.\n", title(b.Name), mdx(b.Doc))

	sb.WriteString("\n## Where it is served\n\n")
	if b.Internal {
		sb.WriteString(
			"Nowhere: it is internal. Other behaviors require it and call its methods\n" +
				"on the same host, so it has no route, no command and no permissions.\n",
		)
	} else {
		sb.WriteString("| Surface | Where |\n| ------- | ----- |\n")
	}
	if b.API {
		fmt.Fprintf(&sb, "| API | `%s`, in [API](/category/api) |\n", b.Path(b.Methods[0]))
	}
	if b.CLI {
		fmt.Fprintf(
			&sb,
			"| CLI | `%s` |\n",
			strings.TrimSuffix(b.Command(b.Methods[0]), " "+b.Methods[0].Name),
		)
	}
	if !b.Internal {
		fmt.Fprintf(&sb, "| Jobs | `behavior.%s.<method>`, run by the agent |\n", b.Name)
	}

	sb.WriteString("\n## Built on\n\n")
	fmt.Fprintf(&sb, "| Uses | Used by |\n| ---- | ------- |\n| %s | %s |\n",
		behaviorLinks(b.Requires), behaviorLinks(behavior.RequiredBy(b)))

	sb.WriteString("\n## Where it runs\n\n")
	if len(b.Platforms) == 0 {
		sb.WriteString("Nowhere yet: it declares no provider with `behavior.Platform`.\n")
	} else {
		names := make([]string, 0, len(b.Platforms))
		for _, pp := range b.Platforms {
			names = append(names, "`"+pp.Name+"`")
		}
		fmt.Fprintf(&sb, "On %s. On any other platform its methods report `skipped`.\n",
			strings.Join(names, ", "))
		for _, m := range b.Methods {
			if len(m.Platforms) == 0 {
				continue
			}
			on := make([]string, 0, len(m.Platforms))
			for _, p := range m.Platforms {
				on = append(on, "`"+p+"`")
			}
			fmt.Fprintf(
				&sb,
				"\n`%s` runs only on %s. On any other platform it reports `skipped`.\n",
				m.Name,
				strings.Join(on, ", "),
			)
		}
	}
	for _, m := range b.Methods {
		for _, p := range [][2]any{{m.SudoPrograms, " with sudo"}, {m.RunsPrograms, ""}} {
			progs := p[0].([]string)
			if len(progs) == 0 {
				continue
			}
			quoted := make([]string, 0, len(progs))
			for _, prog := range progs {
				quoted = append(quoted, "`"+prog+"`")
			}
			fmt.Fprintf(&sb, "\n`%s` runs %s%s, only where it runs.\n",
				m.Name, strings.Join(quoted, ", "), p[1])
		}
	}
	if len(b.Sudo) > 0 {
		progs := make([]string, 0, len(b.Sudo))
		for _, p := range b.Sudo {
			progs = append(progs, "`"+p+"`")
		}
		fmt.Fprintf(
			&sb,
			"\nIt runs %s with sudo, so the agent's user needs a sudoers entry for it\n"+
				"unless the agent runs as root. `osapi agent start` checks this at startup.\n",
			strings.Join(progs, ", "),
		)
	}
	if len(b.Runs) > 0 {
		progs := make([]string, 0, len(b.Runs))
		for _, p := range b.Runs {
			progs = append(progs, "`"+p+"`")
		}
		fmt.Fprintf(
			&sb,
			"\nIt runs %s, which the host must have installed. `osapi agent start`\n"+
				"warns about any that are missing.\n",
			strings.Join(progs, ", "),
		)
	}

	if len(b.Writes) > 0 {
		paths := make([]string, 0, len(b.Writes))
		for _, p := range b.Writes {
			paths = append(paths, "`"+p+"`")
		}
		if slices.Contains(b.Writes, "*") {
			sb.WriteString(
				"\nIt writes the path its caller names. Each behavior that requires it\n" +
					"declares the paths it writes through it.\n",
			)
		} else {
			fmt.Fprintf(&sb, "\nIt writes %s.\n", strings.Join(paths, ", "))
		}
	}
	if spans := behavior.ChildSpans(b); len(spans) > 0 {
		names := make([]string, 0, len(spans))
		for _, sp := range spans {
			names = append(names, "`"+sp+"`")
		}
		fmt.Fprintf(&sb,
			"\nIn a trace, a call is the span `behavior.%s.<method>`, with %s under it.\n",
			b.Name, strings.Join(names, ", "))
	}
	if recorded := spanInputs(b); recorded != "" {
		fmt.Fprintf(&sb, "\nIts span records the input %s.\n", recorded)
	}

	sb.WriteString("\n## Methods\n\n")
	if b.API {
		sb.WriteString(
			"| Method | Verb | Permission | Description |\n| ------ | ---- | ---------- | ----------- |\n",
		)
	} else {
		sb.WriteString("| Method | Verb | Description |\n| ------ | ---- | ----------- |\n")
	}
	for _, m := range b.Methods {
		// Only a behavior with commands has a page per method.
		name := "`" + m.Name + "`"
		if b.CLI {
			name = fmt.Sprintf("[`%s`](%s)", m.Name, CLIPage(b, m))
		}
		if b.API {
			fmt.Fprintf(
				&sb,
				"| %s | %s | `%s` | %s |\n",
				name,
				m.Verb,
				b.Permission(m.Verb),
				mdx(m.Doc),
			)
		} else {
			fmt.Fprintf(&sb, "| %s | %s | %s |\n", name, m.Verb, mdx(m.Doc))
		}
	}

	sb.WriteString("\n## Settings\n\n")
	var settings []config.Key
	for _, k := range config.Keys() {
		if k.Behavior == b.Name {
			settings = append(settings, k)
		}
	}
	if len(settings) == 0 {
		sb.WriteString("None. A behavior declares settings with `behavior.Config`.\n")
	} else {
		fmt.Fprintf(
			&sb,
			"Read by the agent, under `%s` in the config. Each can also be set\n",
			b.SettingsKey(),
		)
		sb.WriteString("with its environment variable or its `osapi agent start` flag.\n\n")
		sb.WriteString("| Key | Flag | Environment | Type | Default | Description |\n")
		sb.WriteString("| --- | ---- | ----------- | ---- | ------- | ----------- |\n")
		for _, k := range settings {
			def := ""
			if k.Default != nil {
				def = "`" + fmt.Sprint(k.Default) + "`"
			}
			fmt.Fprintf(&sb, "| `%s` | `--%s` | `%s` | %s | %s | %s |\n",
				k.Name, k.Flag, k.Env, k.Type, def, mdx(k.Doc))
		}
	}

	fmt.Fprintf(&sb, `
## Inspecting it

`+"```bash"+`
osapi behavior get --name %[1]s                           # surfaces, methods, types, settings, telemetry
osapi behavior method get --name %[1]s --method <method>  # one method, with its JSON Schema
`+"```"+`
`, b.Name)
	return sb.String()
}

// Example is a method's examples as the command lines of its cobra Example,
// each one under a comment that tells what it does.
func Example(
	b *behavior.Behavior,
	m *behavior.Method,
) string {
	command := b.Command(m)
	lines := make([]string, 0, 3*len(m.Examples))
	for i, ex := range m.Examples {
		if i > 0 {
			lines = append(lines, "")
		}
		lines = append(
			lines,
			"  # "+ex.Doc,
			"  "+command+" --target "+exampleHost+exampleArgs(ex.Input),
		)
	}

	return strings.Join(lines, "\n")
}

// Annotations are the docs annotations of a method's command: the
// permission that it needs, and its result, which is what each example does
// on the host and the calls that it refuses.
func Annotations(
	b *behavior.Behavior,
	m *behavior.Method,
) map[string]string {
	out := map[string]string{}
	if b.API {
		out[reference.Permission] = b.Permission(m.Verb)
	}

	var parts []string
	var effects []string
	for _, ex := range m.Examples {
		if len(ex.Effects) == 0 {
			continue
		}
		lines := make([]string, 0, len(ex.Effects))
		for _, e := range ex.Effects {
			lines = append(lines, effectLine(e))
		}
		effects = append(
			effects,
			fmt.Sprintf("| %s | %s |", cell(ex.Doc), cell(strings.Join(lines, "; "))),
		)
	}
	if len(effects) > 0 {
		parts = append(parts, "With the default settings, each example does this on the host:\n\n"+
			"| Example | On the host |\n| --- | --- |\n"+strings.Join(effects, "\n"))
	}

	if len(m.Refusals) > 0 {
		rows := make([]string, 0, len(m.Refusals))
		for _, r := range m.Refusals {
			flags := commandLine(Args(r.Input))
			if flags != "" {
				flags = "`" + flags + "`"
			}
			rows = append(
				rows,
				fmt.Sprintf("| %s | %s | %s |", cell(r.Doc), cell(flags), cell(r.Error)),
			)
		}
		parts = append(parts, "The command fails in these cases:\n\n"+
			"| Call | Flags | Fails with |\n| --- | --- | --- |\n"+strings.Join(rows, "\n"))
	}
	if len(parts) > 0 {
		out[reference.Result] = strings.Join(parts, "\n\n")
	}

	return out
}

// cellEscaper keeps text in one cell of a markdown table: a newline would
// end the row, and a pipe would end the cell.
var cellEscaper = strings.NewReplacer("\n", `\n`, "|", `\|`)

// cell makes s safe in one cell of a markdown table.
func cell(
	s string,
) string {
	return cellEscaper.Replace(s)
}

// GroupAnnotations are the docs annotations of a behavior's own command: a
// note that links to the page of the behavior.
func GroupAnnotations(
	b *behavior.Behavior,
) map[string]string {
	// The command's page is in the directory of its path under the CLI
	// reference, usage/cli, which is two levels under the sidebar.
	words := strings.Fields(strings.TrimPrefix(b.Command(b.Methods[0]), "osapi "))
	up := strings.Repeat("../", 2+len(words)-1)

	return map[string]string{
		reference.Notes: fmt.Sprintf(
			"The [%s behavior](%sbehaviors/%s/%s.md) page tells where the behavior runs, "+
				"what it is built on and its settings.",
			b.Name, up, b.Name, b.Name,
		),
	}
}

// CLIPage is the CLI reference page of a method, relative to the directory
// of the behavior's page.
func CLIPage(
	b *behavior.Behavior,
	m *behavior.Method,
) string {
	words := strings.Fields(strings.TrimPrefix(b.Command(m), "osapi "))

	return "../../usage/cli/" + strings.Join(words, "/") + ".md"
}

// exampleArgs renders an example input as flags, in the input type's field
// order.
func exampleArgs(
	input any,
) string {
	line := commandLine(Args(input))
	if line == "" {
		return ""
	}

	return " " + line
}

// safeArg is an argument a shell reads as it is written.
var safeArg = regexp.MustCompile(`^[A-Za-z0-9_@%+=:,./-]+$`)

// commandLine joins args as a command line a reader can paste: an argument
// with a space or a control character in it is quoted, so a newline shows as
// \n rather than breaking the line, or a table row, it is printed in.
func commandLine(
	args []string,
) string {
	quoted := make([]string, 0, len(args))
	for _, a := range args {
		if !safeArg.MatchString(a) {
			a = strconv.Quote(a)
		}
		quoted = append(quoted, a)
	}

	return strings.Join(quoted, " ")
}

func title(
	s string,
) string {
	return strings.ToUpper(s[:1]) + s[1:]
}

// mdxEscaper escapes what MDX would read as JSX or an expression in prose:
// osapi-<key>.conf is a tag to MDX, and {key} an expression.
var mdxEscaper = strings.NewReplacer("<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;")

// mdx makes text from a behavior definition safe in an .mdx page.
func mdx(
	s string,
) string {
	return mdxEscaper.Replace(s)
}

// effectLine says what one effect does, for a docs page.
func effectLine(
	e behavior.Effect,
) string {
	switch e.Kind {
	case behavior.EffectWrote:
		return fmt.Sprintf("writes `%s`: `%s`", e.Path, strings.TrimRight(e.Content, "\n"))
	case behavior.EffectRemoved:
		return fmt.Sprintf("removes `%s`", e.Path)
	default:
		return fmt.Sprintf("runs `%s`", e.Command)
	}
}

// behaviorLinks are links to the behaviors' pages, or "Nothing".
func behaviorLinks(
	bs []*behavior.Behavior,
) string {
	if len(bs) == 0 {
		return "Nothing"
	}
	links := make([]string, 0, len(bs))
	for _, b := range bs {
		links = append(links, fmt.Sprintf("[%s](../%s/%s.md)", b.Name, b.Name, b.Name))
	}

	return strings.Join(links, ", ")
}

// CatalogPage is every registered behavior in one table, for the Behaviors
// section's landing page to import: what each manages, whether it is served,
// and what it is built on and used by.
func CatalogPage(
	bs []*behavior.Behavior,
) string {
	var sb strings.Builder
	sb.WriteString("{/* Code generated by osapi gen. DO NOT EDIT. */}\n\n")
	sb.WriteString("| Behavior | Manages | Served | Uses | Used by |\n")
	sb.WriteString("| -------- | ------- | ------ | ---- | ------- |\n")
	for _, b := range bs {
		served := "API and CLI"
		switch {
		case b.Internal:
			served = "Internal"
		case b.API && !b.CLI:
			served = "API"
		case !b.API:
			served = "Jobs only"
		}
		fmt.Fprintf(&sb, "| [%s](%s/%s.md) | %s | %s | %s | %s |\n",
			b.Name, b.Name, b.Name, mdx(b.Doc), served,
			names(b.Requires), names(behavior.RequiredBy(b)))
	}

	return sb.String()
}

// names are the behaviors' names, or "-".
func names(
	bs []*behavior.Behavior,
) string {
	if len(bs) == 0 {
		return "-"
	}
	out := make([]string, 0, len(bs))
	for _, b := range bs {
		out = append(out, b.Name)
	}

	return strings.Join(out, ", ")
}

// spanInputs lists the input fields b's methods record on their spans, each
// with the methods that record it: `key` (get, update, delete).
func spanInputs(
	b *behavior.Behavior,
) string {
	byField := map[string][]string{}
	var order []string
	for _, m := range b.Methods {
		for _, f := range m.SpanInputs() {
			if _, ok := byField[f]; !ok {
				order = append(order, f)
			}
			byField[f] = append(byField[f], m.Name)
		}
	}

	parts := make([]string, 0, len(order))
	for _, f := range order {
		parts = append(parts, "`"+f+"` ("+strings.Join(byField[f], ", ")+")")
	}

	return strings.Join(parts, ", ")
}

// ExampleFlags is the flags of an example's command line: --target and the
// flags of input, as the help and the pages write them.
func ExampleFlags(
	input any,
) string {
	return "--target " + exampleHost + exampleArgs(input)
}
