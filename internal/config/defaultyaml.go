package config

import (
	"fmt"
	"reflect"
	"strings"

	"gopkg.in/yaml.v3"
)

// DefaultYAML is the whole config as YAML, each key at its default with its
// doc above it, from Keys: what osapi config default get prints, and the
// start of a config file. A key with no default, a choice of the operator,
// is commented out with why. Thus no sample config is kept by hand.
func DefaultYAML() string {
	var b strings.Builder
	b.WriteString("# The config of osapi: each key at its default. Generated by\n" +
		"# osapi config default get. Keep only the keys that you change.\n")
	var open []string
	for _, k := range Keys() {
		parts := strings.Split(k.Name, ".")
		path, leaf := parts[:len(parts)-1], parts[len(parts)-1]
		same := 0
		for same < len(open) && same < len(path) && open[same] == path[same] {
			same++
		}
		for i := same; i < len(path); i++ {
			if i == 0 {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "%s%s:\n", strings.Repeat("  ", i), path[i])
		}
		open = path
		indent := strings.Repeat("  ", len(path))
		if k.Doc != "" {
			fmt.Fprintf(&b, "%s# %s\n", indent, k.Doc)
		}
		if k.Default == nil {
			fmt.Fprintf(&b, "%s# %s: (%s)\n", indent, leaf, k.Choice)

			continue
		}
		fmt.Fprintf(&b, "%s%s:%s\n", indent, leaf, yamlValue(k.Default, indent))
	}

	return b.String()
}

// yamlValue is v as YAML after a key: inline when it is one line, else a
// block indented under the key.
func yamlValue(
	v any,
	indent string,
) string {
	data, _ := yaml.Marshal(plain(reflect.ValueOf(v)))
	out := strings.TrimSuffix(string(data), "\n")
	if !strings.Contains(out, "\n") {
		return " " + out
	}
	lines := strings.Split(out, "\n")
	for i, l := range lines {
		lines[i] = indent + "  " + l
	}

	return "\n" + strings.Join(lines, "\n")
}

// plain is v with each struct a map by its mapstructure names, as the
// config file spells them, and each empty field left out.
func plain(
	v reflect.Value,
) any {
	switch v.Kind() {
	case reflect.Slice:
		out := make([]any, 0, v.Len())
		for i := range v.Len() {
			out = append(out, plain(v.Index(i)))
		}

		return out
	case reflect.Struct:
		out := map[string]any{}
		for i := range v.NumField() {
			name, _, _ := strings.Cut(v.Type().Field(i).Tag.Get("mapstructure"), ",")
			if name == "" || v.Field(i).IsZero() {
				continue
			}
			out[name] = plain(v.Field(i))
		}

		return out
	default:
		return v.Interface()
	}
}
