package guide

import (
	"fmt"
	"strings"
)

// Term is one part of a DSL or format: how it is written, what it makes
// osapi do, and when to use it.
type Term struct {
	// Kind groups the term, as one of the Spec's Kinds names it.
	Kind string `json:"kind" render:"-"`
	// Name is how the term is written, such as Key("field").
	Name string `json:"name"`
	// Does is what the term makes osapi do.
	Does string `json:"does" label:"-"`
	// When is when to use it.
	When string `json:"when" label:"Use"`
}

// Kind is a group of terms, with the title that spec shows above it.
type Kind struct {
	Kind  string `json:"kind"`
	Title string `json:"title"`
}

// Section is one kind of a Spec and its terms, as the spec command of a
// group prints them: a section for each kind, a block for each term.
type Section struct {
	Kind  string `json:"kind"  render:"-"`
	Title string `json:"title"`
	Terms []Term `json:"terms"            table:"blocks"`
}

// Sections are the kinds of s in order, each with its terms.
func (s Spec) Sections() []Section {
	out := make([]Section, 0, len(s.Kinds))
	for _, k := range s.Kinds {
		out = append(out, Section{Kind: k.Kind, Title: k.Title, Terms: s.Of(k.Kind)})
	}

	return out
}

// Spec is every term of a DSL or format, in groups.
type Spec struct {
	Kinds []Kind `json:"kinds"`
	Terms []Term `json:"terms"`
}

// Of are the terms of kind, in order.
func (s Spec) Of(
	kind string,
) []Term {
	var out []Term
	for _, t := range s.Terms {
		if t.Kind == kind {
			out = append(out, t)
		}
	}

	return out
}

// Check is one rule that a validate command applies: what is required, and
// how to fix what breaks it.
type Check struct {
	// Rule is the name that a problem reports.
	Rule string `json:"rule"`
	// Requires is what must be true.
	Requires string `json:"requires"`
	// Fix is how to fix what breaks the rule.
	Fix string `json:"fix"`
}

// Checks are the rules of a validate command, in order.
type Checks []Check

// Requires is what rule requires, or "" for a rule without a check. A layer
// that checks another layer's rule states it with these words.
func (c Checks) Requires(
	rule string,
) string {
	for _, k := range c {
		if k.Rule == rule {
			return k.Requires
		}
	}

	return ""
}

// Fix is the fix of rule, or "" for a rule without a check.
func (c Checks) Fix(
	rule string,
) string {
	for _, k := range c {
		if k.Rule == rule {
			return k.Fix
		}
	}

	return ""
}

// Help is the list of checks for the help of a validate command, one item
// for each rule.
func (c Checks) Help() string {
	var sb strings.Builder
	for _, k := range c {
		fmt.Fprintf(&sb, "- `%s`: %s Fix: %s\n", k.Rule, k.Requires, k.Fix)
	}

	return sb.String()
}

// mdxEscapes are the characters that MDX reads as the start of a tag, of an
// expression, of a link or of emphasis: Uses[Deps]() is an empty link to it,
// and the text between two asterisks, as in /etc/a/*, /etc/b/*, is italic.
var mdxEscapes = strings.NewReplacer(
	"<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;", "[", "\\[", "*", "\\*",
)

// MDX escapes the characters of s that MDX would parse, outside code spans:
// osapi-<key>.conf is a tag to MDX, {key} an expression and *x* emphasis.
// Inside a code span MDX reads nothing, so the text there stays as it is.
func MDX(
	s string,
) string {
	parts := strings.Split(s, "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = mdxEscapes.Replace(parts[i])
	}

	return strings.Join(parts, "`")
}

// Generated is the first line of the body of each page that a command of
// this binary writes. A writer removes a page with it that it did not write.
const Generated = "<!-- Code generated by osapi cli docs. DO NOT EDIT. -->"

// Markdown is s as a page of the docs site, at position in its sidebar: the
// title, the intro, then a section for each kind with a heading for each
// term, what the term does, and when to use it.
func (s Spec) Markdown(
	title string,
	intro string,
	position int,
) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "---\ntitle: %s\nsidebar_position: %d\n---\n\n%s\n\n# %s\n\n%s\n",
		title, position, Generated, title, intro)
	for _, sec := range s.Sections() {
		if len(sec.Terms) == 0 {
			continue
		}
		fmt.Fprintf(&sb, "\n## %s\n", MDX(sec.Title))
		for _, t := range sec.Terms {
			fmt.Fprintf(&sb, "\n### %s\n\n%s\n\nUse: %s\n", code(t.Name), MDX(t.Does), MDX(t.When))
		}
	}

	return sb.String()
}

// code is s as a code span, with a longer fence when s holds a backtick.
func code(
	s string,
) string {
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}

	return "`" + s + "`"
}
