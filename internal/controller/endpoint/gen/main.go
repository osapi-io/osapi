// Command gen writes the files that come from the endpoint groups: for each
// group that Uses a type, its gen/api.yaml, the routes in gen/api.go and
// the decoders in gen/decode.go, and internal/controller/endpoints/all/gen,
// which registers every group's routes. go generate in
// internal/controller/endpoints/all runs it.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/dave/jennifer/jen"
	"golang.org/x/tools/imports"
	"gopkg.in/yaml.v3"

	"github.com/osapi-io/osapi/internal/controller/endpoint"
	"github.com/osapi-io/osapi/internal/controller/endpoint/gen/commandgen"
	"github.com/osapi-io/osapi/internal/controller/endpoint/gen/routegen"
	_ "github.com/osapi-io/osapi/internal/controller/endpoints/all"
)

// module is the module path, stripped from a package path to find its
// directory in the repository.
const module = "github.com/osapi-io/osapi"

const (
	serverPath    = module + "/internal/controller/endpoint/server"
	commandPath   = module + "/internal/controller/endpoint/command"
	referencePath = module + "/internal/cli/reference"
	cobraPath     = "github.com/spf13/cobra"
	echoPath      = "github.com/labstack/echo/v5"
	allGen        = "internal/controller/endpoints/all/gen"
)

// errorRef is the shared ErrorResponse, from a group's gen directory.
const errorRef = "../../../api/components/gen/api.yaml#/components/schemas/ErrorResponse"

// generated heads every Go file the generator writes.
const generated = "Code generated by internal/controller/endpoint/gen. DO NOT EDIT."

func main() {
	root := flag.String("root", ".", "Repository root to write into")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "endpoint gen:", err)
		os.Exit(1)
	}
}

type writer struct {
	root string
	gofs []string
}

func run(
	root string,
) error {
	w := &writer{root: root}

	var served []*endpoint.Group
	for _, g := range endpoint.All() {
		if problems := endpoint.Validate(g); len(problems) > 0 {
			return fmt.Errorf("%s: %s", g.Name, problems[0])
		}
		if g.Deps != nil {
			served = append(served, g)
		}
	}

	pkgs := make([]string, 0, len(served))
	for _, g := range served {
		pkg := g.Deps.PkgPath()
		dir := filepath.Join(strings.TrimPrefix(pkg, module+"/"), "gen")
		if err := w.clean(dir); err != nil {
			return err
		}
		if err := w.group(g, pkg, dir); err != nil {
			return fmt.Errorf("%s: %w", g.Name, err)
		}
		pkgs = append(pkgs, pkg+"/gen")
	}
	if err := w.registry(pkgs); err != nil {
		return err
	}

	return w.format()
}

func (w *writer) group(
	g *endpoint.Group,
	pkg string,
	dir string,
) error {
	doc, err := endpoint.OpenAPI(g, errorRef)
	if err != nil {
		return err
	}
	raw, err := json.Marshal(doc)
	if err != nil {
		return err
	}
	var tree any
	if err := json.Unmarshal(raw, &tree); err != nil {
		return err
	}
	var spec bytes.Buffer
	spec.WriteString("# " + generated + "\n")
	enc := yaml.NewEncoder(&spec)
	enc.SetIndent(2)
	if err := enc.Encode(tree); err != nil {
		return err
	}
	if err := w.write(filepath.Join(dir, "api.yaml"), spec.Bytes()); err != nil {
		return err
	}

	api := newFile(pkg)
	routegen.Routes(api, g, pkg)
	if err := w.goFile(filepath.Join(dir, "api.go"), api); err != nil {
		return err
	}

	decode := newFile(pkg)
	routegen.Decoders(decode, g)
	if err := w.goFile(filepath.Join(dir, "decode.go"), decode); err != nil {
		return err
	}

	cli := newFile(pkg)
	commandgen.Commands(cli, g, pkg)

	return w.goFile(filepath.Join(dir, "cli.go"), cli)
}

// newFile is a file of a group's gen package.
func newFile(
	pkg string,
) *jen.File {
	f := jen.NewFilePathName(pkg+"/gen", "gen")
	f.HeaderComment(generated)
	f.ImportName(serverPath, "server")
	f.ImportName(echoPath, "echo")
	f.ImportName(pkg, pkg[strings.LastIndex(pkg, "/")+1:])

	return f
}

// registry is internal/controller/endpoints/all/gen/gen.go: one blank
// import of each group's gen package, so the controller registers every
// group's routes by importing it.
func (w *writer) registry(
	pkgs []string,
) error {
	sort.Strings(pkgs)
	f := jen.NewFilePathName(module+"/"+allGen, "gen")
	f.HeaderComment(generated)
	f.PackageComment("Package gen registers the routes of every endpoint group that is served.")
	for _, p := range pkgs {
		f.Anon(p)
	}
	if err := w.clean(allGen); err != nil {
		return err
	}

	return w.goFile(filepath.Join(allGen, "gen.go"), f)
}

// clean removes the generated files in dir, so a method or a group that is
// gone leaves nothing behind.
func (w *writer) clean(
	dir string,
) error {
	entries, err := os.ReadDir(filepath.Join(w.root, dir))
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, e := range entries {
		p := filepath.Join(w.root, dir, e.Name())
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(data, []byte("// Code generated")) ||
			bytes.HasPrefix(data, []byte("# Code generated")) {
			if err := os.Remove(p); err != nil {
				return err
			}
		}
	}

	return nil
}

func (w *writer) write(
	rel string,
	data []byte,
) error {
	p := filepath.Join(w.root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}

	return os.WriteFile(p, data, 0o644)
}

// goFile renders f to rel, with the imports in the repository's three
// groups.
func (w *writer) goFile(
	rel string,
	f *jen.File,
) error {
	var buf bytes.Buffer
	if err := f.Render(&buf); err != nil {
		return fmt.Errorf("%s: %w", rel, err)
	}
	imports.LocalPrefix = module
	src, err := imports.Process(rel, buf.Bytes(), &imports.Options{
		Comments: true, TabIndent: true, TabWidth: 8, FormatOnly: true,
	})
	if err != nil {
		return fmt.Errorf("%s: %w", rel, err)
	}
	w.gofs = append(w.gofs, rel)

	return w.write(rel, src)
}

// format runs the repository's formatters over every Go file written.
func (w *writer) format() error {
	args := append([]string{
		"tool", "github.com/segmentio/golines",
		"--base-formatter=go tool mvdan.cc/gofumpt", "-w",
	}, w.gofs...)
	cmd := exec.Command("go", args...)
	cmd.Dir = w.root
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("format: %w: %s", err, out)
	}

	return nil
}
