package authtoken

import (
	"fmt"
	"strings"
)

// TypeScriptFile is where the UI keeps the permissions TypeScript writes,
// from the root of the repository.
const TypeScriptFile = "ui/src/lib/permissions.gen.ts"

// TypeScript is the UI's list of permissions and the permissions of each
// built-in role, as TypeScript, from AllPermissions and RolePermissions.
// go generate ./internal/behaviors/all writes it to TypeScriptFile, with
// every behavior registered, so the UI checks the permissions that a token
// can have. A test fails when the file is stale.
func TypeScript() string {
	var sb strings.Builder
	sb.WriteString("// Code generated by go generate ./internal/behaviors/all. DO NOT EDIT.\n")
	sb.WriteString("// From AllPermissions and RolePermissions in internal/authtoken.\n\n")

	all := AllPermissions()
	sb.WriteString("export type Permission =\n")
	for i, p := range all {
		end := ""
		if i == len(all)-1 {
			end = ";"
		}
		fmt.Fprintf(&sb, "  | %q%s\n", p, end)
	}

	sb.WriteString("\nexport const ALL_PERMISSIONS: Permission[] = [\n")
	for _, p := range all {
		fmt.Fprintf(&sb, "  %q,\n", p)
	}
	sb.WriteString("];\n")

	sb.WriteString("\n/** The permissions of each built-in role, by its JWT role. */\n")
	sb.WriteString("export const ROLE_PERMISSIONS: Record<string, Permission[]> = {\n")
	for _, role := range Roles() {
		perms, _ := RolePermissions(role)
		quoted := make([]string, 0, len(perms))
		for _, p := range perms {
			quoted = append(quoted, fmt.Sprintf("%q", p))
		}
		// Prettier keeps an array on one line when it fits in 80 columns,
		// and the file must be what Prettier writes.
		if line := "  " + string(
			role,
		) + ": [" + strings.Join(
			quoted,
			", ",
		) + "],"; len(
			line,
		) <= 80 {
			sb.WriteString(line + "\n")

			continue
		}
		fmt.Fprintf(&sb, "  %s: [\n", role)
		for _, q := range quoted {
			fmt.Fprintf(&sb, "    %s,\n", q)
		}
		sb.WriteString("  ],\n")
	}
	sb.WriteString("};\n")

	return sb.String()
}
