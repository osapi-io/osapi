package authtoken

import (
	"fmt"
	"go/format"
	"strings"
)

// GoFile is where the SDK keeps the permission constants that Go writes,
// from the root of the repository.
const GoFile = "pkg/sdk/client/permissions.gen.go"

// Go is the SDK's constant for each permission, from AllPermissions, and for
// each built-in role, from Roles: a behavior's permission has one, as a
// hand-written domain's and an endpoint group's do. go
// generate ./internal/behaviors/all writes it to GoFile, and a test fails
// when the file is stale.
func Go() string {
	var sb strings.Builder
	sb.WriteString("// Code generated by go generate ./internal/behaviors/all. DO NOT EDIT.\n")
	sb.WriteString("// From AllPermissions in internal/authtoken.\n\n")
	sb.WriteString(
		"package client\n\n// Permission constants, one for each permission osapi knows.\nconst (\n",
	)
	for _, p := range AllPermissions() {
		fmt.Fprintf(&sb, "\t%s Permission = %q\n", ConstName(p), p)
	}
	sb.WriteString(")\n\n// Built-in role constants, one for each built-in role.\nconst (\n")
	for _, r := range Roles() {
		fmt.Fprintf(&sb, "\tRole%s Role = %q\n", capital(r), r)
	}
	sb.WriteString(")\n")
	// The source is a const block of names and strings, which formats.
	out, _ := format.Source([]byte(sb.String()))

	return string(out)
}

// ConstName is the name of the SDK's constant for permission p: Perm, then
// the resource and the verb, each with a capital, such as PermDiskRead for
// disk:read.
func ConstName(
	p Permission,
) string {
	resource, verb, _ := strings.Cut(p, ":")

	return "Perm" + capital(resource) + capital(verb)
}

// capital is s with its first letter a capital.
func capital(
	s string,
) string {
	if s == "" {
		return s
	}

	return strings.ToUpper(s[:1]) + s[1:]
}

// RoleTable is the permissions of each built-in role as a markdown table,
// for the configuration page of the docs site.
func RoleTable() string {
	var sb strings.Builder
	sb.WriteString("| Role | Permissions |\n| --- | --- |\n")
	for _, role := range Roles() {
		perms, _ := RolePermissions(role)
		names := make([]string, 0, len(perms))
		for _, p := range perms {
			names = append(names, "`"+p+"`")
		}
		fmt.Fprintf(&sb, "| `%s` | %s |\n", role, strings.Join(names, ", "))
	}

	return strings.TrimSuffix(sb.String(), "\n")
}
