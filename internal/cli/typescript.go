package cli

import (
	"fmt"
	"maps"
	"slices"
	"strings"
)

// StatusTypeScriptFile is where the UI keeps the tones that StatusTypeScript
// writes, from the repository's root.
const StatusTypeScriptFile = "ui/src/lib/status.gen.ts"

// StatusTypeScript is StatusTones as TypeScript, for the UI: each status word
// and its tone, so a badge shows a word in the color the CLI prints it in.
// go generate ./internal/behaviors/all writes it to StatusTypeScriptFile, and
// a test fails when the file is stale.
func StatusTypeScript() string {
	var sb strings.Builder
	sb.WriteString("// Code generated by go generate ./internal/behaviors/all. DO NOT EDIT.\n")
	sb.WriteString("// From StatusTones in internal/cli/theme.go.\n\n")
	sb.WriteString("export type Tone = \"ok\" | \"warn\" | \"err\";\n\n")
	sb.WriteString("/** The tone of each status word, as the CLI colors it. */\n")
	sb.WriteString("export const STATUS_TONES: Record<string, Tone> = {\n")
	for _, word := range slices.Sorted(maps.Keys(StatusTones)) {
		fmt.Fprintf(&sb, "  %s: %q,\n", word, StatusTones[word])
	}
	sb.WriteString("};\n")

	return sb.String()
}
