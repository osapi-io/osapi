// Package cli holds what the commands of the CLI share: the printer, the
// theme, the tables and the help.
package cli

import (
	"fmt"
	"strings"

	"github.com/charmbracelet/lipgloss"
)

// DocsPaletteCSSFile and DocsPaletteTSFile are where the docs site keeps
// the palette that DocsPaletteCSS and DocsPaletteTS write, from the
// repository's root.
const (
	DocsPaletteCSSFile = "docs/src/css/palette.gen.css"
	DocsPaletteTSFile  = "docs/src/palette.gen.ts"
)

// docsColors are the colors of the docs site for one page theme: the
// headings in page order, the accent color and the gray.
type docsColors struct {
	headings []lipgloss.Color
	accent   lipgloss.Color
	gray     lipgloss.Color
}

// docsStatus are the status colors of the docs site's notes: ok, attention
// and wrong, as the CLI prints them. Yellow is a 256-color, so it is given
// as the hex that the UI uses for it.
var docsStatus = [][2]string{
	{"ok", string(Green)},
	{"warn", "#ffd787"},
	{"error", string(Red)},
}

// docsDark is the dark page: the colors of the CLI and the UI. docsLight is
// the light page: the dark tints of the same colors, which read on white,
// as the README's logo-light.svg does.
var (
	docsDark = docsColors{
		headings: headingColors,
		accent:   LogoBlue,
		gray:     LogoGray,
	}
	docsLight = docsColors{
		headings: tinted(headingColors),
		accent:   LogoBlue,
		gray:     LogoGray,
	}
)

// tinted is the tint of each color.
func tinted(
	colors []lipgloss.Color,
) []lipgloss.Color {
	out := make([]lipgloss.Color, 0, len(colors))
	for _, c := range colors {
		out = append(out, tints[c])
	}

	return out
}

// DocsPaletteCSS is the palette as CSS variables for the docs site's
// stylesheet: the light page's on :root and the dark page's under
// [data-theme='dark']. go generate ./internal/behaviors/all writes it to
// DocsPaletteCSSFile, and a test fails when the file is stale.
func DocsPaletteCSS() string {
	var sb strings.Builder
	sb.WriteString("/* Code generated by go generate ./internal/behaviors/all. DO NOT EDIT. */\n")
	sb.WriteString(
		"/* From the palette of internal/cli/theme.go, as the UI and the CLI use it. */\n\n",
	)
	sb.WriteString(":root {\n")
	writeDocsVars(&sb, docsLight)
	sb.WriteString("}\n\n[data-theme='dark'] {\n")
	writeDocsVars(&sb, docsDark)
	sb.WriteString("}\n")

	return sb.String()
}

// writeDocsVars writes the variables of c.
func writeDocsVars(
	sb *strings.Builder,
	c docsColors,
) {
	for i, h := range c.headings {
		fmt.Fprintf(sb, "  --osapi-heading-%d: %s;\n", i+1, h)
	}
	fmt.Fprintf(sb, "  --osapi-accent: %s;\n", c.accent)
	fmt.Fprintf(sb, "  --osapi-gray: %s;\n", c.gray)
	for _, st := range docsStatus {
		fmt.Fprintf(sb, "  --osapi-%s: %s;\n", st[0], st[1])
	}
}

// DocsPaletteTS is the palette as TypeScript, for the docs site's code
// blocks: docusaurus.config.ts builds its Prism themes from it. go generate
// ./internal/behaviors/all writes it to DocsPaletteTSFile, and a test fails
// when the file is stale.
func DocsPaletteTS() string {
	var sb strings.Builder
	sb.WriteString("// Code generated by go generate ./internal/behaviors/all. DO NOT EDIT.\n")
	sb.WriteString(
		"// From the palette of internal/cli/theme.go, as the UI and the CLI use it.\n\n",
	)
	sb.WriteString("export const palette = {\n")
	writeDocsTS(&sb, "light", docsLight)
	writeDocsTS(&sb, "dark", docsDark)
	sb.WriteString("} as const;\n")

	return sb.String()
}

// writeDocsTS writes the colors of c as the entry name of palette.
func writeDocsTS(
	sb *strings.Builder,
	name string,
	c docsColors,
) {
	quoted := make([]string, 0, len(c.headings))
	for _, h := range c.headings {
		quoted = append(quoted, fmt.Sprintf("%q", string(h)))
	}
	fmt.Fprintf(sb, "  %s: {\n", name)
	fmt.Fprintf(sb, "    headings: [%s],\n", strings.Join(quoted, ", "))
	fmt.Fprintf(sb, "    accent: %q,\n", string(c.accent))
	fmt.Fprintf(sb, "    gray: %q,\n", string(c.gray))
	sb.WriteString("  },\n")
}
