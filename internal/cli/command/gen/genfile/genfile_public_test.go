package genfile_test

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/dave/jennifer/jen"
	"github.com/stretchr/testify/suite"

	"github.com/osapi-io/osapi/internal/cli/command/gen/genfile"
)

type GenfilePublicTestSuite struct {
	suite.Suite

	root string
}

func (s *GenfilePublicTestSuite) SetupTest() {
	s.root = s.T().TempDir()
}

// put writes content at rel under the root, as a file a run made before.
func (s *GenfilePublicTestSuite) put(
	rel string,
	content string,
) {
	p := filepath.Join(s.root, rel)
	s.Require().NoError(os.MkdirAll(filepath.Dir(p), 0o755))
	s.Require().NoError(os.WriteFile(p, []byte(content), 0o644))
}

// read is the content at rel under the root, or "" when it is not there.
func (s *GenfilePublicTestSuite) read(
	rel string,
) string {
	data, err := os.ReadFile(filepath.Join(s.root, rel))
	if os.IsNotExist(err) {
		return ""
	}
	s.Require().NoError(err)

	return string(data)
}

// named is a type that jennifer cannot write as a literal.
type named string

// goFile is a Go file of package gen with one constant, value.
func goFile(
	value any,
) *jen.File {
	f := jen.NewFile("gen")
	f.HeaderComment("// Code generated by a test. DO NOT EDIT.")
	f.Const().Id("Value").Op("=").Lit(value)

	return f
}

func (s *GenfilePublicTestSuite) TestRun() {
	const old = "// Code generated by a test. DO NOT EDIT.\n\npackage gen\n\nconst Old = 1\n"
	tests := []struct {
		name         string
		run          func(w *genfile.Writer) error
		wantErr      string
		validateFunc func()
	}{
		{
			name: "when a file fails to render, nothing on disk changes",
			run: func(w *genfile.Writer) error {
				if err := w.Clean("pkg/gen"); err != nil {
					return err
				}
				if err := w.Go("pkg/gen/a.go", goFile("a")); err != nil {
					return err
				}

				return w.Go("pkg/gen/b.go", goFile(named("b")))
			},
			wantErr: "pkg/gen/b.go: unsupported type for literal",
			validateFunc: func() {
				s.Equal(old, s.read("pkg/gen/old.go"), "the file of the last run stays")
				s.Equal(
					old,
					s.read("pkg/gen/a.go"),
					"a file rendered before the failure is not written",
				)
				s.Equal("package gen\n", s.read("pkg/gen/hand.go"))
			},
		},
		{
			name: "when the run succeeds, stale files go and new ones are written",
			run: func(w *genfile.Writer) error {
				if err := w.Clean("pkg/gen"); err != nil {
					return err
				}
				if err := w.Go("pkg/gen/a.go", goFile("a")); err != nil {
					return err
				}
				if err := w.Write(
					"pkg/gen/api.yaml",
					[]byte("# Code generated\nopenapi: 3.0.0\n"),
				); err != nil {
					return err
				}
				if err := w.Remove("pkg/other.go"); err != nil {
					return err
				}
				if err := w.Remove("pkg/missing.go"); err != nil {
					return err
				}
				if err := w.Registry(
					"pkg/all/gen",
					"// Code generated by a test. DO NOT EDIT.",
					[]string{"Package gen registers each package."},
					[]string{
						"github.com/osapi-io/osapi/pkg/b",
						"github.com/osapi-io/osapi/pkg/a",
					},
				); err != nil {
					return err
				}

				return w.Flush()
			},
			validateFunc: func() {
				s.Empty(s.read("pkg/gen/old.go"), "a generated file that no run writes is removed")
				s.Contains(s.read("pkg/gen/a.go"), `const Value = "a"`)
				s.Equal("# Code generated\nopenapi: 3.0.0\n", s.read("pkg/gen/api.yaml"))
				s.Equal("package gen\n", s.read("pkg/gen/hand.go"), "a file a person wrote stays")
				s.Empty(s.read("pkg/other.go"))
				reg := s.read("pkg/all/gen/gen.go")
				s.Less(
					indexOf(reg, "osapi/pkg/a"),
					indexOf(reg, "osapi/pkg/b"),
					"the registry imports in order",
				)
			},
		},
		{
			name: "when the directory to clean is not there",
			run: func(w *genfile.Writer) error {
				if err := w.Clean("none/gen"); err != nil {
					return err
				}

				return w.Flush()
			},
			validateFunc: func() {
				s.Equal(old, s.read("pkg/gen/old.go"))
			},
		},
		{
			name: "when the directory to clean cannot be read",
			run: func(w *genfile.Writer) error {
				return w.Clean("pkg/gen/hand.go")
			},
			wantErr: "not a directory",
		},
		{
			name: "when the directory to clean holds a directory",
			run: func(w *genfile.Writer) error {
				s.put("pkg/gen/sub/x.go", "package sub\n")

				return w.Clean("pkg/gen")
			},
			wantErr: "is a directory",
		},
		{
			name: "when the registry's directory cannot be read",
			run: func(w *genfile.Writer) error {
				return w.Registry(
					"pkg/gen/hand.go",
					"// Code generated by a test. DO NOT EDIT.",
					nil,
					nil,
				)
			},
			wantErr: "not a directory",
		},
		{
			name: "when a file's directory cannot be made",
			run: func(w *genfile.Writer) error {
				if err := w.Write("pkg/gen/hand.go/x.go", []byte("x")); err != nil {
					return err
				}

				return w.Flush()
			},
			wantErr: "not a directory",
		},
		{
			name: "when a file's directory cannot be written",
			run: func(w *genfile.Writer) error {
				dir := filepath.Join(s.root, "pkg/gen")
				s.Require().NoError(os.Chmod(dir, 0o555))
				s.T().Cleanup(func() { _ = os.Chmod(dir, 0o755) })
				if err := w.Write("pkg/gen/new.go", []byte("x")); err != nil {
					return err
				}

				return w.Flush()
			},
			wantErr: "permission denied",
		},
		{
			name: "when a directory is where a file goes",
			run: func(w *genfile.Writer) error {
				s.put("pkg/gen/dir.go/x", "x")
				if err := w.Write("pkg/gen/dir.go", []byte("x")); err != nil {
					return err
				}

				return w.Flush()
			},
			wantErr: "pkg/gen/dir.go",
			validateFunc: func() {
				entries, err := os.ReadDir(filepath.Join(s.root, "pkg/gen"))
				s.Require().NoError(err)
				for _, e := range entries {
					s.NotContains(e.Name(), ".dir.go.", "the temporary file is removed")
				}
			},
		},
		{
			name: "when a stale path cannot be removed",
			run: func(w *genfile.Writer) error {
				if err := w.Remove("pkg/gen"); err != nil {
					return err
				}

				return w.Flush()
			},
			wantErr: "directory not empty",
		},
		{
			name: "when a Go file does not parse",
			run: func(w *genfile.Writer) error {
				f := jen.NewFile("gen")
				f.Op("}")

				return w.Go("pkg/gen/bad.go", f)
			},
			wantErr: "pkg/gen/bad.go",
		},
	}

	for _, tc := range tests {
		s.Run(tc.name, func() {
			s.root = s.T().TempDir()
			s.put("pkg/gen/old.go", old)
			s.put("pkg/gen/a.go", old)
			s.put("pkg/gen/hand.go", "package gen\n")
			s.put("pkg/other.go", "package pkg\n")

			err := tc.run(&genfile.Writer{Root: s.root})
			if tc.wantErr != "" {
				s.Require().Error(err)
				s.Contains(err.Error(), tc.wantErr)
			} else {
				s.Require().NoError(err)
			}
			if tc.validateFunc != nil {
				tc.validateFunc()
			}
		})
	}
}

// indexOf is the index of sub in s, or -1.
func indexOf(
	s string,
	sub string,
) int {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}

	return -1
}

func TestGenfilePublicTestSuite(
	t *testing.T,
) {
	suite.Run(t, new(GenfilePublicTestSuite))
}
