// Command generate writes the files that come from the local groups: for
// each group, the cobra commands in gen/cli.go, and
// internal/cli/commands/all/gen, which registers every group's commands. go
// generate in internal/cli/commands/all runs it.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/dave/jennifer/jen"

	"github.com/osapi-io/osapi/internal/cli/command"
	commandgen "github.com/osapi-io/osapi/internal/cli/command/gen"
	"github.com/osapi-io/osapi/internal/cli/command/gen/genfile"
	_ "github.com/osapi-io/osapi/internal/cli/commands/all"
	"github.com/osapi-io/osapi/internal/wiring"
)

// module is the module path, stripped from a package path to find its
// directory in the repository.
const module = "github.com/osapi-io/osapi"

// allGen registers every local group's commands.
const allGen = "internal/cli/commands/all/gen"

// generated heads every Go file the generator writes.
const generated = "Code generated by internal/cli/command/gen/generate. DO NOT EDIT."

func main() {
	root := flag.String("root", ".", "Repository root to write into")
	flag.Parse()
	if err := errors.Join(run(*root), wiring.Take()); err != nil {
		fmt.Fprintln(os.Stderr, "command gen:", err)
		os.Exit(1)
	}
}

func run(
	root string,
) error {
	w := &genfile.Writer{Root: root}

	groups := command.All()
	pkgs := make([]string, 0, len(groups))
	for _, g := range groups {
		if problems := command.Validate(g); len(problems) > 0 {
			return fmt.Errorf("%s: %s", g.Name, problems[0])
		}
		pkg := pkgOf(g)
		dir := filepath.Join(strings.TrimPrefix(pkg, module+"/"), "gen")
		if err := w.Clean(dir); err != nil {
			return err
		}
		f := jen.NewFilePathName(pkg+"/gen", "gen")
		f.HeaderComment(generated)
		f.ImportName(pkg, pkg[strings.LastIndex(pkg, "/")+1:])
		commandgen.Commands(f, g, pkg)
		if err := w.Go(filepath.Join(dir, "cli.go"), f); err != nil {
			return fmt.Errorf("%s: %w", g.Name, err)
		}
		pkgs = append(pkgs, pkg+"/gen")
	}

	if err := w.Registry(
		allGen,
		generated,
		[]string{"Package gen registers the commands of every local group."},
		pkgs,
	); err != nil {
		return err
	}

	return w.Flush()
}

// pkgOf is the package of g's definition: the package of the type it Uses.
func pkgOf(
	g *command.LocalGroup,
) string {
	return reflect.Zero(g.Deps).Type().PkgPath()
}
