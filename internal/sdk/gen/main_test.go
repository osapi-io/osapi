// genSuite has a root with the test spec, and the helpers of the suites of
// the generator. It has no tests of its own.
type genSuite struct {
	suite.Suite

	root string
}

type MainTestSuite struct {
	genSuite
}

func (s *genSuite) SetupTest() {
	s.root = s.T().TempDir()
	spec, err := os.ReadFile("sdkmodel/testdata/spec.yaml")
	s.Require().NoError(err)
	s.write("internal/controller/api/gen/api.yaml", string(spec))
	// A type a person wrote, and a file of the last run that is gone now.
	s.write(dir+"/written.go", "package client\n\ntype ErrorResponse struct{}\n")
	s.write(dir+"/gone.gen.go", header+"\n\npackage client\n")
	s.write(
		dir+"/permissions.gen.go",
		"// Code generated by another. DO NOT EDIT.\n\npackage client\n",
	)
}

func (s *genSuite) write(
	rel string,
	text string,
) {
	path := filepath.Join(s.root, rel)
	s.Require().NoError(os.MkdirAll(filepath.Dir(path), 0o755))
	s.Require().NoError(os.WriteFile(path, []byte(text), 0o644))
}

func (s *genSuite) read(
	rel string,
) string {
	data, err := os.ReadFile(filepath.Join(s.root, dir, rel))
	s.Require().NoError(err)

	return string(data)
}

func (s *MainTestSuite) TestRun() {
	s.Require().NoError(generate(s.root, false))

	tests := []struct {
		name         string
		validateFunc func()
	}{
		{
			name: "when a method sends its path, its query and its body",
			validateFunc: func() {
				dns := s.read("network_dns.gen.go")
				s.Contains(dns, "func (s *NetworkDNSService) Update(\n\tctx context.Context,\n"+
					"\thostname string,\n\tinput NetworkDNSUpdateInput,\n"+
					") (*Response[Collection[DnsEntry]], error) {")
				s.Contains(dns, "InterfaceName string `json:\"-\"`")
				s.Contains(dns, "OverrideDHCP bool `json:\"override_dhcp,omitempty\"`")
				s.Contains(dns, `url.PathEscape(input.InterfaceName), nil, input)`)
				s.Contains(
					dns,
					`"/api/node/"+url.PathEscape(hostname)+"/network/dns/"+url.PathEscape(interfaceName)`,
				)
				s.Contains(dns, "the permission dns:read.")
				s.Contains(s.read("network_dns_types.gen.go"),
					"// DnsKind: The kind of a resolver.\ntype DnsKind string\n",
					"a string schema is a string type")
				s.Contains(
					s.read("network_dns_types.gen.go"),
					"Kind DnsKind `json:\"kind,omitzero\"`",
				)
				job := s.read("job.gen.go")
				s.Contains(job, "type JobListParams struct {")
				s.Contains(job, `q.Set("limit", strconv.Itoa(params.Limit))`)
				s.Contains(job, `q.Set("all", strconv.FormatBool(params.All))`)
				s.Contains(job, ") error {\n\treturn sendEmpty(")
				s.Contains(s.read("node_file.gen.go"), `q.Set("path", path)`)
			},
		},
		{
			name: "when a multipart method is left to a person",
			validateFunc: func() {
				s.NotContains(s.read("file.gen.go"), "Upload(")
			},
		},
		{
			name: "when a type a person wrote is not written again",
			validateFunc: func() {
				s.NotContains(s.read("network_dns_types.gen.go"), "type ErrorResponse struct")
				s.Contains(s.read("network_dns_types.gen.go"), "type DnsEntry struct")
			},
		},
		{
			name: "when the services are on the client, and the old files are gone",
			validateFunc: func() {
				s.Contains(
					s.read("services.gen.go"),
					"s.NetworkDNS = &NetworkDNSService{client: c}",
				)
				s.NoFileExists(filepath.Join(s.root, dir, "gone.gen.go"))
				s.FileExists(filepath.Join(s.root, dir, "permissions.gen.go"))
				s.FileExists(filepath.Join(s.root, dir, "written.go"))
			},
		},
	}

	for _, tc := range tests {
		s.Run(tc.name, func() {
			tc.validateFunc()
		})
	}
}

func (s *MainTestSuite) TestRunErrors() {
	s.Run("when the spec is not there", func() {
		s.Error(generate(filepath.Join(s.root, "none"), false))
	})
	s.Run("when the spec is not a model", func() {
		s.write("internal/controller/api/gen/api.yaml",
			"openapi: 3.0.0\ninfo: {title: t, version: '1'}\n"+
				"x-osapi-areas: [{name: fleet, label: Fleet}]\npaths:\n"+
				"  /api/x:\n    get:\n      operationId: X\n      tags: [Nope]\n"+
				"      responses: {'200': {description: ok}}\n")
		s.ErrorContains(generate(s.root, false), "no tag of the spec")
	})
}

func TestMainTestSuite(
	t *testing.T,
) {
	suite.Run(t, new(MainTestSuite))
}

// replaceOnce is text with the first old replaced by repl.
func replaceOnce(
	text string,
	old string,
	repl string,
) string {
	return strings.Replace(text, old, repl, 1)
}
