// pageDir is the SDK's section of the docs site, from the root of the
// repository. The page of each service is in the folder of its area, such
// as fleet/agent.md, and the _category_.json of the folder gives the area's
// label and order, from the spec's x-osapi-areas, as the folders of the
// feature pages are. The generator owns the folder of each area, and fills
// the table of services of indexPage. The folder libraryDir, with the
// client's overview and the guidelines, is written by hand and comes last.
const pageDir = "docs/docs/sidebar/sdk"

// libraryDir is the folder of pageDir that people write: the client's
// overview, the guidelines and platform detection.
const libraryDir = "library"

// indexPage is the client's overview, whose table of services the
// generator fills.
const indexPage = libraryDir + "/client.md"

// categoryFile is the file of a folder of the docs site that gives its
// label and its place in the sidebar.
const categoryFile = "_category_.json"

// pageHeader heads each page this generator writes, under its front
// matter.
const pageHeader = "<!-- Code generated by internal/sdk/gen. DO NOT EDIT. -->"

// exampleURL is where a reader finds the SDK's examples.
const exampleURL = "https://github.com/osapi-io/osapi/blob/main/" + exampleDir + "/"

// goMethod is a method of a service as the SDK's source declares it, a
// generated one or one a person wrote.
type goMethod struct {
	// Name is the method's name, such as Get.
	Name string
	// Doc is its doc comment.
	Doc string
	// Signature is its declaration, as gofmt writes it.
	Signature string
	// Params are the names of its parameters.
	Params []string
	// Returns are its results but the error, such as
	// *Response[Collection[NetworkDnsEntry]].
	Returns string
}

// runPages writes the SDK's reference pages from the model of the spec and
// the methods of the SDK's source, which run writes first.
func runPages(
	root string,
	m *sdkmodel.Model,
) error {
	methods, err := sourceMethods(filepath.Join(root, dir))
	if err != nil {
		return err
	}
	w := &genfile.Writer{Root: root}
	users := typeUsers(m)
	removeOld(w, root)
	for i, a := range m.Areas {
		if !slices.ContainsFunc(
			m.Services,
			func(s *sdkmodel.Service) bool { return s.Area == a.Name },
		) {
			continue
		}
		// The areas come first, in their order, as on the feature pages.
		_ = w.Write(filepath.Join(pageDir, a.Name, categoryFile),
			fmt.Appendf(nil, "{\n  \"label\": %q,\n  \"position\": %d\n}\n", a.Label, i+1))
	}
	for _, s := range m.Services {
		cs, err := calls(s)
		if err != nil {
			return err
		}
		page := servicePage(s, methods[s.Name+"Service"], cs, serviceTypes(m, users, s))
		if len(cs) > 0 {
			page += examplesSection(s)
		}
		_ = w.Write(pagePath(s), []byte(page))
	}

	index := filepath.Join(pageDir, indexPage)
	data, err := os.ReadFile(filepath.Join(root, index))
	if err != nil {
		return err
	}
	_ = w.Write(index, []byte(guide.Fill(string(data), "sdk-services", func([]string) string {
		return serviceTables(m)
	})))

	if err := w.Flush(); err != nil {
		return err
	}
	removeEmpty(root)

	return nil
}

// removeEmpty removes each folder of pageDir that is empty, such as the
// folder of an area that has no service now, so the docs site does not show
// it as a section with no pages. A folder that is not empty stays.
func removeEmpty(
	root string,
) {
	entries, _ := os.ReadDir(filepath.Join(root, pageDir))
	for _, e := range entries {
		if e.IsDir() {
			_ = os.Remove(filepath.Join(root, pageDir, e.Name()))
		}
	}
}

// removeOld records the removal of each page that a run wrote before, in
// pageDir and in the folder of each area, and of each area folder's
// categoryFile, so an area or a service that is gone leaves nothing behind.
// Each folder but libraryDir is an area's, so the folder of an area that
// is gone goes too.
func removeOld(
	w *genfile.Writer,
	root string,
) {
	old, _ := os.ReadDir(filepath.Join(root, pageDir))
	for _, e := range old {
		name := filepath.Join(pageDir, e.Name())
		if !e.IsDir() {
			data, err := os.ReadFile(filepath.Join(root, name))
			if err == nil && strings.Contains(string(data), pageHeader) {
				_ = w.Remove(name)
			}

			continue
		}
		if e.Name() == libraryDir {
			continue
		}
		_ = w.Remove(filepath.Join(name, categoryFile))
		pages, _ := os.ReadDir(filepath.Join(root, name))
		for _, p := range pages {
			page := filepath.Join(name, p.Name())
			data, err := os.ReadFile(filepath.Join(root, page))
			if err == nil && strings.Contains(string(data), pageHeader) {
				_ = w.Remove(page)
			}
		}
	}
}

// pagePath is the page of s, in the folder of its area, from the root of
// the repository.
func pagePath(
	s *sdkmodel.Service,
) string {
	return filepath.Join(pageDir, s.Area, snake(s.Name)+".md")
}

// serviceTables is the tables of the services of client.md: one for each
// area that has a service, under its label, in the order of the areas, with
// its services in the order of their names.
func serviceTables(
	m *sdkmodel.Model,
) string {
	var parts []string
	for _, a := range m.Areas {
		rows := []string{"### " + a.Label, "", "| Service | Description |", "| --- | --- |"}
		for _, s := range m.Services {
			if s.Area == a.Name {
				rows = append(rows, fmt.Sprintf("| [%s](../%s/%s.md) | %s |",
					s.Name, a.Name, snake(s.Name), cell(sentence(s.Doc))))
			}
		}
		if len(rows) > 4 {
			parts = append(parts, strings.Join(rows, "\n"))
		}
	}

	return strings.Join(parts, "\n\n")
}

// serviceTypes is the types that the methods of s send and receive, in the
// order of their names, with the Input of each method.
func serviceTypes(
	m *sdkmodel.Model,
	users map[string]map[string]bool,
	s *sdkmodel.Service,
) []*sdkmodel.Type {
	var out []*sdkmodel.Type
	for _, meth := range s.Methods {
		if meth.Input != nil {
			out = append(out, meth.Input)
		}
	}
	for _, t := range m.Types {
		if users[t.Name][s.Name] {
			out = append(out, t)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })

	return out
}

// servicePage is the reference page of s.
func servicePage(
	s *sdkmodel.Service,
	methods []*goMethod,
	cs []*call,
	types []*sdkmodel.Type,
) string {
	byName := map[string]*sdkmodel.Method{}
	for _, meth := range s.Methods {
		byName[meth.Name] = meth
	}
	examples := map[string][]*call{}
	for _, c := range cs {
		examples[c.Method.Name] = append(examples[c.Method.Name], c)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "---\ntitle: %s\n---\n\n%s\n\n# %s\n\n", s.Name, pageHeader, s.Name)
	fmt.Fprintf(&b, "`c.%s` calls the API's %s group. %s\n\n", s.Name, s.Name, sentence(s.Doc))

	b.WriteString(
		"## Methods\n\n| Method | Returns | Permission | Description |\n| --- | --- | --- | --- |\n",
	)
	for _, gm := range methods {
		perm := ""
		if meth := byName[gm.Name]; meth != nil && meth.Permission != "" {
			perm = "`" + meth.Permission + "`"
		}
		returns := ""
		if gm.Returns != "" {
			returns = "`" + gm.Returns + "`"
		}
		fmt.Fprintf(&b, "| [`%s(%s)`](#%s) | %s | %s | %s |\n", gm.Name,
			strings.Join(gm.Params, ", "), strings.ToLower(gm.Name), returns, perm,
			cell(summary(gm, byName[gm.Name])))
	}

	for _, gm := range methods {
		fmt.Fprintf(&b, "\n### %s\n\n```go\n%s\n```\n\n", gm.Name, gm.Signature)
		meth := byName[gm.Name]
		if meth == nil {
			// A method that is not an operation has its doc comment.
			b.WriteString(strings.TrimSpace(gm.Doc) + "\n")
			b.WriteString("\nIt is not an operation of the API: it runs in the client.\n")

			continue
		}
		if meth.Multipart {
			// A person wrote the method of a form: its doc comment says
			// what it does on the client too.
			b.WriteString(strings.TrimSpace(gm.Doc) + "\n")
		} else {
			b.WriteString(methodText(meth))
		}
		for i, c := range examples[gm.Name] {
			if i == 0 {
				b.WriteString("\nThe examples of the method's definition:\n")
			}
			fmt.Fprintf(&b, "\n%s, `go run %s.go %s`:\n\n```go\n%s\n```\n",
				strings.TrimSuffix(sentence(c.Doc), "."), snake(s.Name), c.Name, callText(c, meth))
		}
	}

	if len(types) > 0 {
		b.WriteString(
			"\n## Types\n\nThe fields of each type are the properties of its schema in the API's spec.\n",
		)
		for _, t := range types {
			fmt.Fprintf(&b, "\n### %s\n\n", t.Name)
			if doc := sentence(t.Doc); doc != "" {
				b.WriteString(doc + "\n\n")
			}
			if t.Scalar != "" {
				fmt.Fprintf(&b, "A `%s`.\n", t.Scalar)

				continue
			}
			b.WriteString("| Field | Type | Description |\n| --- | --- | --- |\n")
			for _, f := range t.Fields {
				fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", f.GoName, f.Type, cell(fieldDoc(f)))
			}
		}
	}

	return b.String()
}

// examplesSection is the section of a page that links the program of the
// examples of s.
func examplesSection(
	s *sdkmodel.Service,
) string {
	return fmt.Sprintf("\n## Example\n\n[`%s/%s.go`](%s%s.go) runs each example of this page. "+
		"With no argument, it lists them.\n", exampleDir, snake(s.Name), exampleURL, snake(s.Name))
}

// callText is the code of the example c, as its program has it.
func callText(
	c *call,
	m *sdkmodel.Method,
) string {
	var pre strings.Builder
	for _, p := range c.Pre {
		pre.WriteString(strings.TrimSpace(fmt.Sprintf("%#v", p)) + "\n")
	}
	code := fmt.Sprintf("%#v", c.Code)
	if m.Result == nil {
		return pre.String() + "err := " + code
	}

	return pre.String() + "resp, err := " + code
}

// summary is what a method does, in one sentence: the summary of its
// operation, or the first sentence of the doc comment of a method a person
// wrote.
func summary(
	gm *goMethod,
	m *sdkmodel.Method,
) string {
	if m != nil && m.Summary != "" {
		return sentence(m.Summary)
	}

	return firstSentence(gm.Doc)
}

// methodText is what the page says of m, a method that the generator
// writes: its summary, its description, and the request it sends.
func methodText(
	m *sdkmodel.Method,
) string {
	var parts []string
	if m.Summary != "" {
		parts = append(parts, sentence(m.Summary))
	}
	if m.Description != "" {
		parts = append(parts, sentence(m.Description))
	}
	send := fmt.Sprintf("It sends `%s %s`", m.HTTPMethod, m.Path)
	if m.Permission != "" {
		send += fmt.Sprintf(", and needs the permission `%s`.", m.Permission)
	} else {
		send += ", and needs no permission."
	}
	parts = append(parts, send)

	return strings.Join(parts, "\n\n") + "\n"
}

// fieldDoc is the description of a field of a type.
func fieldDoc(
	f *sdkmodel.Field,
) string {
	doc := sentence(f.Doc)
	if len(f.Enum) > 0 {
		doc += " It is one of: " + strings.Join(f.Enum, ", ") + "."
	}
	if f.Path {
		doc = "The " + f.Name + " of the path. " + doc
	}

	return strings.TrimSpace(doc)
}

// firstSentence is the first sentence of a doc comment.
func firstSentence(
	doc string,
) string {
	doc = strings.Join(strings.Fields(doc), " ")
	if i := strings.Index(doc, ". "); i >= 0 {
		return doc[:i+1]
	}

	return doc
}

// cell is text for a cell of a table: on one line, with each pipe escaped.
func cell(
	text string,
) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}

// sourceMethods is the exported methods of each type of the SDK's package
// in dir, by the type's name, in the order of the source: the generated
// methods and the ones a person wrote.
func sourceMethods(
	dir string,
) (map[string][]*goMethod, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	out := map[string][]*goMethod{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range f.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || !fd.Name.IsExported() {
				continue
			}
			recv := receiver(fd)
			out[recv] = append(out[recv], sourceMethod(fset, fd))
		}
	}

	return out, nil
}

// receiver is the name of the type of fd's receiver.
func receiver(
	fd *ast.FuncDecl,
) string {
	t := fd.Recv.List[0].Type
	if star, ok := t.(*ast.StarExpr); ok {
		t = star.X
	}
	if id, ok := t.(*ast.Ident); ok {
		return id.Name
	}

	return ""
}

// sourceMethod is the method that fd declares.
func sourceMethod(
	fset *token.FileSet,
	fd *ast.FuncDecl,
) *goMethod {
	gm := &goMethod{Name: fd.Name.Name, Doc: fd.Doc.Text()}
	var buf bytes.Buffer
	decl := &ast.FuncDecl{Recv: fd.Recv, Name: fd.Name, Type: fd.Type}
	// Printing a declaration that the parser read cannot fail.
	_ = printer.Fprint(&buf, fset, decl)
	gm.Signature = buf.String()
	for _, p := range fd.Type.Params.List {
		for _, n := range p.Names {
			gm.Params = append(gm.Params, n.Name)
		}
	}
	var results []string
	fails := false
	if fd.Type.Results != nil {
		for _, r := range fd.Type.Results.List {
			buf.Reset()
			_ = printer.Fprint(&buf, fset, r.Type)
			if buf.String() == "error" {
				fails = true

				continue
			}
			results = append(results, buf.String())
		}
	}
	gm.Returns = strings.Join(results, ", ")
	if gm.Returns == "" && fails {
		gm.Returns = "error"
	}

	return gm
}
