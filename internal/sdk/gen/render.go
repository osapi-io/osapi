// header heads each file this generator writes.
const header = "// Code generated by internal/sdk/gen. DO NOT EDIT."

// pkg is the import path of the SDK.
const pkg = "github.com/osapi-io/osapi/pkg/sdk/client"

// typesPkg is the import path of the SDK's shared types.
const typesPkg = "github.com/osapi-io/osapi/pkg/sdk/types"

// shared is the types that pkg/sdk/types declares, which run reads first. A
// reference to one is types.Name.
var shared = map[string]bool{}

// files is each file of the SDK that m makes, by its name. A type in
// written, which a person wrote in the package, is not written again.
func files(
	m *sdkmodel.Model,
	written map[string]bool,
) map[string]*jen.File {
	out := map[string]*jen.File{}
	users := typeUsers(m)
	shared := newFile()
	byService := map[string][]*sdkmodel.Type{}
	for _, t := range m.Types {
		if written[t.Name] {
			continue
		}
		if u := users[t.Name]; len(u) == 1 {
			for s := range u {
				byService[s] = append(byService[s], t)
			}

			continue
		}
		writeType(shared, t)
	}
	out["types.gen.go"] = shared

	for _, s := range m.Services {
		f := newFile()
		writeService(f, s)
		out[snake(s.Name)+".gen.go"] = f
		if types := byService[s.Name]; len(types) > 0 {
			tf := newFile()
			for _, t := range types {
				writeType(tf, t)
			}
			out[snake(s.Name)+"_types.gen.go"] = tf
		}
	}

	wiring := newFile()
	writeServices(wiring, m)
	out["services.gen.go"] = wiring

	return out
}

// newFile is a new generated file of the SDK.
func newFile() *jen.File {
	f := jen.NewFilePathName(pkg, "client")
	f.HeaderComment(strings.TrimPrefix(header, "// "))

	return f
}

// typeUsers is the services that use each type, by the type's name, through
// a method's parameters, body or result, or a field of a type they use.
// A parameter's type is an enum, such as GetJobsStatus.
func typeUsers(
	m *sdkmodel.Model,
) map[string]map[string]bool {
	byName := map[string]*sdkmodel.Type{}
	for _, t := range m.Types {
		byName[t.Name] = t
	}
	users := map[string]map[string]bool{}
	var visit func(service string, t *sdkmodel.TypeRef)
	visit = func(service string, t *sdkmodel.TypeRef) {
		if t == nil {
			return
		}
		if t.Kind != sdkmodel.Named {
			visit(service, t.Elem)

			return
		}
		if users[t.Name] == nil {
			users[t.Name] = map[string]bool{}
		}
		if users[t.Name][service] {
			return
		}
		users[t.Name][service] = true
		for _, f := range byName[t.Name].Fields {
			visit(service, f.Type)
		}
	}
	for _, s := range m.Services {
		for _, meth := range s.Methods {
			for _, p := range append(slices.Clone(meth.PathParams), meth.Query...) {
				visit(s.Name, p.Type)
			}
			if meth.Input != nil {
				for _, f := range meth.Input.Fields {
					visit(s.Name, f.Type)
				}
			}
			visit(s.Name, meth.Result)
		}
	}

	return users
}

// writeServices writes the struct that holds each service, which Client
// embeds, and the function that makes them.
func writeServices(
	f *jen.File,
	m *sdkmodel.Model,
) {
	fields := make([]jen.Code, 0, len(m.Services))
	makes := make([]jen.Code, 0, len(m.Services))
	for i, s := range m.Services {
		if i > 0 {
			fields = append(fields, jen.Line())
		}
		comment(&fields, s.Name+" calls the API's "+s.Name+" group: "+lowerFirst(sentence(s.Doc)))
		fields = append(fields, jen.Id(s.Name).Op("*").Id(s.Name+"Service"))
		makes = append(makes, jen.Id("s").Dot(s.Name).Op("=").Op("&").Id(s.Name+"Service").
			Values(jen.Dict{jen.Id("client"): jen.Id("c")}))
	}
	f.Comment("services are the typed services of the SDK, one for each group of the API.")
	f.Comment("Client embeds them, so c.NetworkDNS is a service of the client c.")
	f.Type().Id("services").Struct(fields...)
	f.Line()
	f.Comment("wire makes each service, which sends its requests through c.")
	f.Func().Params(jen.Id("s").Op("*").Id("services")).Id("wire").
		Params(jen.Id("c").Op("*").Id("Client")).Block(makes...)
}

// writeService writes s: its struct, the parameters of its methods and its
// methods.
func writeService(
	f *jen.File,
	s *sdkmodel.Service,
) {
	name := s.Name + "Service"
	fileComment(f, name+" calls the API's "+s.Name+" group: "+lowerFirst(sentence(s.Doc)))
	f.Type().Id(name).Struct(jen.Id("client").Op("*").Id("Client"))
	for _, m := range s.Methods {
		if m.Multipart {
			continue
		}
		f.Line()
		if opt := m.OptionalQuery(); len(opt) > 0 {
			writeParams(f, s, m, opt)
			f.Line()
		}
		if m.Input != nil {
			writeInput(f, s, m)
		}
		writeMethod(f, s, m)
	}
}

// paramsName is the name of the struct of a method's optional parameters.
func paramsName(
	s *sdkmodel.Service,
	m *sdkmodel.Method,
) string {
	return s.Name + m.Name + "Params"
}

// writeParams writes the struct of the optional parameters of m's query.
func writeParams(
	f *jen.File,
	s *sdkmodel.Service,
	m *sdkmodel.Method,
	params []*sdkmodel.Param,
) {
	fields := make([]jen.Code, 0, len(params))
	for i, p := range params {
		if i > 0 {
			fields = append(fields, jen.Line())
		}
		comment(&fields, p.GoName+" is the "+p.Name+" of the query: "+
			lowerFirst(sentence(p.Doc))+" The zero value leaves it out.")
		fields = append(fields, jen.Id(p.GoName).Add(typeCode(p.Type)))
	}
	fileComment(f, paramsName(s, m)+" are the parameters of "+s.Name+"Service."+m.Name+
		" that a request can leave out.")
	f.Type().Id(paramsName(s, m)).Struct(fields...)
}

// writeMethod writes the method m of s.
func writeMethod(
	f *jen.File,
	s *sdkmodel.Service,
	m *sdkmodel.Method,
) {
	doc := m.Name + " is the operation " + m.OperationID
	if m.Summary != "" {
		doc += ": " + lowerFirst(sentence(m.Summary))
	} else {
		doc += "."
	}
	fileComment(f, doc)
	if m.Description != "" {
		f.Comment("")
		fileComment(f, sentence(m.Description))
	}
	f.Comment("")
	send := "It sends " + m.HTTPMethod + " " + m.Path
	if m.Permission != "" {
		send += ", and needs the permission " + m.Permission
	}
	fileComment(f, send+".")

	args := []jen.Code{jen.Id("ctx").Qual("context", "Context")}
	if t := m.Target(); t != nil {
		args = append(args, jen.Id(t.ArgName).Add(typeCode(t.Type)))
	}
	if m.Input != nil {
		args = append(args, jen.Id("input").Id(m.Input.Name))
	} else {
		for _, p := range m.Keys() {
			args = append(args, jen.Id(p.ArgName).Add(typeCode(p.Type)))
		}
		for _, p := range m.RequiredQuery() {
			args = append(args, jen.Id(p.ArgName).Add(typeCode(p.Type)))
		}
	}
	optional := m.OptionalQuery()
	if len(optional) > 0 {
		args = append(args, jen.Id("params").Id(paramsName(s, m)))
	}

	var body []jen.Code
	query := jen.Nil()
	if len(m.Query) > 0 {
		query = jen.Id("q")
		body = append(body, jen.Id("q").Op(":=").Qual("net/url", "Values").Values())
		for _, p := range m.RequiredQuery() {
			body = append(
				body,
				jen.Id("q").Dot("Set").Call(jen.Lit(p.Name), format(p.Type, jen.Id(p.ArgName))),
			)
		}
		for _, p := range optional {
			v := jen.Id("params").Dot(p.GoName)
			body = append(body, jen.If(v.Clone().Op("!=").Add(zero(p.Type))).Block(
				jen.Id("q").Dot("Set").Call(jen.Lit(p.Name), format(p.Type, v.Clone())),
			))
		}
	}
	reqBody := jen.Nil()
	if m.Input != nil {
		reqBody = jen.Id("input")
	}
	call := []jen.Code{
		jen.Id("ctx"),
		jen.Id("s").Dot("client"),
		verb(m.HTTPMethod),
		pathCode(m),
		query,
		reqBody,
	}

	var results jen.Code
	if m.Result == nil {
		results = jen.Error()
		body = append(body, jen.Return(jen.Id("sendEmpty").Call(call...)))
	} else {
		results = jen.Parens(jen.List(
			jen.Op("*").Id("Response").Types(typeCode(m.Result)),
			jen.Error(),
		))
		body = append(body, jen.Return(jen.Id("send").Types(typeCode(m.Result)).Call(call...)))
	}

	f.Func().Params(jen.Id("s").Op("*").Id(s.Name + "Service")).Id(m.Name).
		Params(multi(args)...).Add(results).Block(body...)
}

// multi puts each of codes on a line of its own, as the repository writes
// the parameters of a function.
func multi(
	codes []jen.Code,
) []jen.Code {
	out := make([]jen.Code, 0, len(codes)+1)
	for _, c := range codes {
		out = append(out, jen.Line().Add(c))
	}

	return append(out, jen.Line())
}

// verb is the net/http constant of an HTTP method.
func verb(
	method string,
) jen.Code {
	name := map[string]string{
		http.MethodGet:    "MethodGet",
		http.MethodPost:   "MethodPost",
		http.MethodPut:    "MethodPut",
		http.MethodDelete: "MethodDelete",
	}[method]

	return jen.Qual("net/http", name)
}

// pathCode is the expression of m's path, with each parameter escaped.
func pathCode(
	m *sdkmodel.Method,
) jen.Code {
	byName := map[string]*sdkmodel.Param{}
	for _, p := range m.PathParams {
		byName[p.Name] = p
	}
	var parts []jen.Code
	lit := ""
	for _, seg := range strings.Split(strings.TrimPrefix(m.Path, "/"), "/") {
		lit += "/"
		if !strings.HasPrefix(seg, "{") {
			lit += seg

			continue
		}
		parts = append(parts, jen.Lit(lit))
		lit = ""
		p := byName[strings.Trim(seg, "{}")]
		v := jen.Id(p.ArgName)
		if m.Input != nil && p != m.Target() {
			v = jen.Id("input").Dot(p.GoName)
		}
		if p.Type.Kind == sdkmodel.Named || p.Type.Name == "string" {
			parts = append(parts, jen.Qual("net/url", "PathEscape").Call(format(p.Type, v)))
		} else {
			parts = append(parts, format(p.Type, v))
		}
	}
	if lit != "" {
		parts = append(parts, jen.Lit(lit))
	}
	out := jen.Add(parts[0])
	for _, p := range parts[1:] {
		out = out.Op("+").Add(p)
	}

	return out
}

// format is the text of v, a scalar or an enum of type t, for a path or a
// query.
func format(
	t *sdkmodel.TypeRef,
	v *jen.Statement,
) jen.Code {
	if t.Kind == sdkmodel.Named {
		return jen.String().Call(v)
	}
	switch t.Name {
	case "int":
		return jen.Qual("strconv", "Itoa").Call(v)
	case "int64":
		return jen.Qual("strconv", "FormatInt").Call(v, jen.Lit(10))
	case "float64":
		return jen.Qual("strconv", "FormatFloat").
			Call(v, jen.LitRune('f'), jen.Lit(-1), jen.Lit(64))
	case "bool":
		return jen.Qual("strconv", "FormatBool").Call(v)
	default:
		return v
	}
}

// zero is the zero value of a scalar or an enum of type t.
func zero(
	t *sdkmodel.TypeRef,
) jen.Code {
	if t.Kind == sdkmodel.Named {
		return jen.Lit("")
	}
	switch t.Name {
	case "string":
		return jen.Lit("")
	case "bool":
		return jen.False()
	default:
		return jen.Lit(0)
	}
}

// writeInput writes the Input of m: a field for each key of the path, which
// the body leaves out, then the fields of the body.
func writeInput(
	f *jen.File,
	s *sdkmodel.Service,
	m *sdkmodel.Method,
) {
	fileComment(f, m.Input.Name+" is the input of "+s.Name+"Service."+m.Name+
		". A field of the path goes in the path, and each other field in the body.")
	writeFields(f, m.Input)
	f.Line()
}

// writeEnum writes a constant for each value of t, an enum, such as
// ContentTypeRaw for the value raw of ContentType.
func writeEnum(
	f *jen.File,
	t *sdkmodel.Type,
) {
	if len(t.Enum) == 0 {
		return
	}
	f.Comment("The values of " + t.Name + ".")
	consts := make([]jen.Code, 0, len(t.Enum))
	for _, v := range t.Enum {
		consts = append(consts, jen.Id(t.Name+sdkmodel.GoName(v)).Id(t.Name).Op("=").Lit(v))
	}
	f.Const().Defs(consts...)
	f.Line()
}

// writeType writes t, a struct with a field for each property, or the
// scalar type under it, such as a string for an enum.
func writeType(
	f *jen.File,
	t *sdkmodel.Type,
) {
	doc := t.Name + " is the " + t.Name + " of the spec."
	if s := sentence(t.Doc); s != "" {
		doc = t.Name + ": " + s
	}
	fileComment(f, doc)
	if t.Scalar != "" {
		f.Type().Id(t.Name).Id(t.Scalar)
		f.Line()
		writeEnum(f, t)

		return
	}
	writeFields(f, t)
	f.Line()
}

// writeFields writes the struct of t.
func writeFields(
	f *jen.File,
	t *sdkmodel.Type,
) {
	fields := make([]jen.Code, 0, len(t.Fields))
	for i, fd := range t.Fields {
		if i > 0 {
			fields = append(fields, jen.Line())
		}
		doc := sentence(fd.Doc)
		if doc == "" {
			doc = fd.GoName + " is the property " + fd.Name + "."
		}
		if len(fd.Enum) > 0 {
			doc += " It is one of: " + strings.Join(fd.Enum, ", ") + "."
		}
		if fd.Path {
			doc = "The " + fd.Name + " of the path"
			if fd.Doc != "" {
				doc += ": " + lowerFirst(sentence(fd.Doc))
			} else {
				doc += "."
			}
		}
		comment(&fields, doc)
		tag := fd.Name
		switch {
		case fd.Path:
			tag = "-"
		case !fd.Required:
			if fd.Type.Kind == sdkmodel.Named ||
				(fd.Type.Kind == sdkmodel.Scalar && fd.Type.Name == "time.Time") {
				tag += ",omitzero"
			} else {
				tag += ",omitempty"
			}
		}
		fields = append(
			fields,
			jen.Id(fd.GoName).Add(typeCode(fd.Type)).Tag(map[string]string{"json": tag}),
		)
	}
	f.Type().Id(t.Name).Struct(fields...)
}

// typeCode is the Go type of t.
func typeCode(
	t *sdkmodel.TypeRef,
) jen.Code {
	switch t.Kind {
	case sdkmodel.Slice:
		return jen.Index().Add(typeCode(t.Elem))
	case sdkmodel.Map:
		return jen.Map(jen.String()).Add(typeCode(t.Elem))
	case sdkmodel.Collection:
		return jen.Id("Collection").Types(typeCode(t.Elem))
	case sdkmodel.Any:
		return jen.Any()
	case sdkmodel.Named:
		if shared[t.Name] {
			return jen.Qual(typesPkg, t.Name)
		}

		return jen.Id(t.Name)
	}
	if t.Name == "time.Time" {
		return jen.Qual("time", "Time")
	}

	return jen.Id(t.Name)
}

// comment adds text to codes as a comment, wrapped.
func comment(
	codes *[]jen.Code,
	text string,
) {
	for _, line := range strings.Split(wrap(text), "\n") {
		*codes = append(*codes, jen.Comment(line))
	}
}

// fileComment adds text to f as a comment, wrapped.
func fileComment(
	f *jen.File,
	text string,
) {
	for _, line := range strings.Split(wrap(text), "\n") {
		f.Comment(line)
	}
}

// sentence is text, trimmed, that ends with a full stop.
func sentence(
	text string,
) string {
	text = strings.Join(strings.Fields(text), " ")
	if text == "" || strings.HasSuffix(text, ".") {
		return text
	}

	return text + "."
}

// lowerFirst is text with its first letter small, unless the first word is
// a name in capitals, such as DNS.
func lowerFirst(
	text string,
) string {
	if len(text) < 2 || unicode.IsUpper(rune(text[1])) {
		return text
	}

	return strings.ToLower(text[:1]) + text[1:]
}

// wrap breaks text into lines of at most 76 characters.
func wrap(
	text string,
) string {
	var lines []string
	line := ""
	for _, w := range strings.Fields(text) {
		if line != "" && len(line)+1+len(w) > 76 {
			lines = append(lines, line)
			line = w

			continue
		}
		if line != "" {
			line += " "
		}
		line += w
	}

	return strings.Join(append(lines, line), "\n")
}

// snake is the file name of a Go name, such as network_dns for NetworkDNS.
func snake(
	name string,
) string {
	var b strings.Builder
	r := []rune(name)
	for i, c := range r {
		if i > 0 && unicode.IsUpper(c) &&
			(unicode.IsLower(r[i-1]) || (i+1 < len(r) && unicode.IsLower(r[i+1]))) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToLower(c))
	}

	return b.String()
}
